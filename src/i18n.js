export const STRINGS = { en, hi };
export const GLOSSARY = { en: enGlossary, hi: hiGlossary };
export const LANGS = ['en', 'hi'];

/** Look up a string with an optional business-type override and {var} substitution. */
export function translate(lang, key, vars, type) {
  const dict = STRINGS[lang] || en;
  let s = (type && (dict[`${key}.${type}`] ?? en[`${key}.${type}`])) ?? dict[key] ?? en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}

const inr = new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR', maximumFractionDigits: 0 });
const plain = new Intl.NumberFormat('en-IN', { maximumFractionDigits: 0 });
const one = new Intl.NumberFormat('en-IN', { maximumFractionDigits: 1, minimumFractionDigits: 1 });

/** ₹1,23,456 (always rounds to whole rupees; "−" for negatives). */
export function formatINR(n) {
  if (!Number.isFinite(n)) return '₹0';
  const r = Math.round(n);
  return (r < 0 ? '−' : '') + inr.format(Math.abs(r));
}

/** 1,23,456 without the ₹ sign (for inputs). */
export function formatPlain(n) {
  return Number.isFinite(n) ? plain.format(n) : '';
}

/** ₹4.4 lakh / ₹1.2 crore for headlines; falls back to ₹ format below 1 lakh. */
export function formatShort(n, lang = 'en') {
  if (!Number.isFinite(n)) return '₹0';
  const a = Math.abs(n);
  const sign = n < 0 ? '−' : '';
  const t = (k) => translate(lang, k);
  const trim = (x) => one.format(x).replace(/\.0$/, '');
  if (a >= 1e7) return `${sign}₹${trim(a / 1e7)} ${t('fmt.crore')}`;
  if (a >= 1e5) return `${sign}₹${trim(a / 1e5)} ${t('fmt.lakh')}`;
  return formatINR(n);
}

/** "₹3.2" for the per-₹100 view: one decimal under 10, whole numbers above. */
export function formatPer100(n) {
  if (!Number.isFinite(n)) return '₹0';
  const a = Math.abs(n);
  const s = a < 10 ? one.format(a).replace(/\.0$/, '') : plain.format(Math.round(a));
  return `${n < -0.0001 && s !== '0' ? '−' : ''}₹${s}`;
}

/** "9.2%" */
export function formatPct(n) {
  if (!Number.isFinite(n)) return '0%';
  const a = Math.abs(n);
  return `${n < 0 ? '−' : ''}${a < 10 ? one.format(a).replace(/\.0$/, '') : plain.format(Math.round(a))}%`;
}
